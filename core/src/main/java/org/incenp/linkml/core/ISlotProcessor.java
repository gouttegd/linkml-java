package org.incenp.linkml.core;

/**
 * An interface representing an arbitrary operation to perform on the slots of a
 * LinkML object.
 * <p>
 * This interface is intended to allow the "batch" processing of slots.
 */
public interface ISlotProcessor {

    /**
     * Performs the operation for the given slot of the given object.
     * 
     * @param slot   The slot that is being processed.
     * @param object The object to which the slot belongs.
     * @param value  The current value of the slot in the object. May be
     *               <code>null</code>.
     * @throws LinkMLRuntimeException If any error occurs during the operation.
     */
    public void process(Slot slot, Object object, Object value) throws LinkMLRuntimeException;
}
